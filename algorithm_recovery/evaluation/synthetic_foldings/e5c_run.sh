#!/usr/bin/env bash
# E5.C one design: generate -> self-check -> synth_ice40 -> bench2 spec -> prepare -> frozen C1 pipeline -> graph -> score.
# usage: e5c_run.sh SEED N CONTROL   (CONTROL = none | chain | rotate); results in build/e5c/<case>/
set -uo pipefail
seed=$1; N=$2; control=$3
H=/home/jiahao/hal; E=$H/algorithm_recovery/evaluation; B=$H/build
case=e5c_s${seed}_n${N}$([ "$control" = none ] || echo _$control)
D=$B/e5c/$case; G=$D/gen
[ -e "$D/score.json" ] && { echo "$case: done"; exit 0; }
if [ -s "$D/case/graph/graph_training.json" ]; then   # pipeline already done: score only
    ( ulimit -v 4194304; timeout 3600 "$B/python_venv/bin/python" "$E/synthetic_foldings/e5c_score.py" "$D/case" "$G/truth.json" "$G/fold_top.json" \
        "$D/case/graph/graph_training.json" "$D/score.json" ) > "$D/score.log" 2>&1
    echo "$case: $(tail -n 1 "$D/score.log" | cut -c1-400)"; exit 0
fi
mkdir -p "$G"
python3 "$E/synthetic_foldings/e5c_gen.py" "$seed" "$N" "$G" --control "$control" > "$G/gen.json" || { echo "$case: generator refused"; exit 0; }
python3 "$E/synthetic_foldings/e5c_selfcheck.py" "$G" > "$G/selfcheck.json" || { echo "$case: SELF-CHECK FAILED"; exit 1; }
( ulimit -v 4194304; cd "$G" && timeout 1200 yosys -q -l synth.log -p "read_verilog fold_top.v; synth_ice40 -top fold_top -nobram -json fold_top.json; tee -o stat.txt stat" ) > /dev/null 2>&1 || { echo "$case: synthesis failed"; exit 1; }
python3 - "$G" "$N" "$case" <<'PY'
import json, sys
g, N, case = sys.argv[1], int(sys.argv[2]), sys.argv[3]
t = json.load(open(f"{g}/truth.json"))
spec = {"synth": f"{g}/fold_top.json", "top": "fold_top",
        "source": {"url": "generated by e5c_gen.py", "commit": "see hal git log", "license": "n/a", "author": "E5.C generator",
                   "category": "synthetic folding", "parameters": f"seed={t['seed']} N={N} control={t['control']}"},
        "clock": "clk", "non_data": ["rst"], "defaults": {"rst": 0}, "prefix": [{"cycles": 2, "values": {"rst": 1}}],
        "period": N, "schedule": {}, "data_mode": "hold", "case": case, "transactions": 128, "training_transactions": 64,
        "seed": 20261103}
json.dump(spec, open(f"{g}/spec.json", "w"), indent=1)
PY
[ -e "$D/case" ] && mv "$D/case" "$D/case.prev.$(date +%s)"   # keep an earlier attempt; never delete
python3 "$E/library_designs/prepare_bench2.py" "$G/spec.json" "$D/case" > "$D/prepare.log" 2>&1 || { echo "$case: prepare failed"; exit 1; }
# C1 pipeline with the event graph (case/graph/), each stage <= 6 GiB as in E5/E8
( ulimit -v 6291456; bash "$E/library_designs/run_bench2.sh" "$D/case" ) > /dev/null 2>&1
( ulimit -v 4194304; timeout 3600 "$B/python_venv/bin/python" "$E/synthetic_foldings/e5c_score.py" "$D/case" "$G/truth.json" "$G/fold_top.json" \
    "$D/case/graph/graph_training.json" "$D/score.json" ) > "$D/score.log" 2>&1
echo "$case: $(tail -n 1 "$D/score.log" | cut -c1-400)"
