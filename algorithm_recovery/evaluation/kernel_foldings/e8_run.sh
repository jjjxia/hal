#!/usr/bin/env bash
# E8.2 one design (E8_PREMISES_PROTOCOL.txt): fold kernel -> self-check -> synth_ice40 -> bench2 spec -> prepare ->
# frozen C1 pipeline -> graph -> E8 scorer. As e5c/e5c_run.sh, with the E8 generator/self-check/scorer and a 6 GiB budget.
# usage: e8_run.sh KERNEL NSPEC POLICY SEED        results in build/e8/fold/<kernel>_<nspec>_<policy>/
set -uo pipefail
kernel=$1; nspec=$2; policy=$3; seed=$4
H=/home/jiahao/hal; E=$H/algorithm_recovery/evaluation; B=$H/build
case=${kernel}_${nspec}_${policy}
D=$B/e8/fold/$case; G=$D/gen
[ -e "$D/score.json" ] && { echo "$case: done"; exit 0; }
mkdir -p "$G"
[ -s "$G/truth.json" ] || python3 "$E/kernel_foldings/e8_fold_dfg.py" "$kernel" "$nspec" "$policy" "$seed" "$G" > "$G/gen.json" || { echo "$case: generator failed"; exit 1; }
python3 "$E/kernel_foldings/e8_selfcheck.py" "$G" 100 > "$G/selfcheck.json" || { echo "$case: SELF-CHECK FAILED"; exit 1; }
( ulimit -v ${VMEM_KB:-6291456}; cd "$G" && timeout 3600 yosys -q -l synth.log -p "read_verilog fold_top.v; synth_ice40 -top fold_top -nobram -json fold_top.json; tee -o stat.txt stat" ) > /dev/null 2>&1 || { echo "$case: synthesis failed"; exit 1; }
python3 - "$G" "$case" <<'PY'
import json, sys
g, case = sys.argv[1], sys.argv[2]
t = json.load(open(f"{g}/truth.json"))
spec = {"synth": f"{g}/fold_top.json", "top": "fold_top",
        "source": {"url": "generated by e8/e8_fold_dfg.py", "commit": "see hal git log", "license": "n/a", "author": "E8 generator",
                   "category": "folded kernel", "parameters": f"kernel={t['kernel']} N={t['N']} policy={t['policy']} seed={t['seed']}"},
        "clock": "clk", "non_data": ["rst"], "defaults": {"rst": 0}, "prefix": [{"cycles": 2, "values": {"rst": 1}}],
        "period": t["N"], "schedule": {}, "data_mode": "hold", "case": case, "transactions": 128, "training_transactions": 64,
        "seed": 20261104}
json.dump(spec, open(f"{g}/spec.json", "w"), indent=1)
PY
[ -e "$D/case" ] && mv "$D/case" "$D/case.prev.$(date +%s)"
( ulimit -v ${VMEM_KB:-6291456}; timeout 10800 python3 "$E/library_designs/prepare_bench2.py" "$G/spec.json" "$D/case" ) > "$D/prepare.log" 2>&1 || { echo "$case: prepare failed"; exit 1; }
( ulimit -v ${VMEM_KB:-6291456}; bash "$E/library_designs/run_bench2.sh" "$D/case" ) > /dev/null 2>&1
cli=$B/bin/hal_plugins/hal-recover
export HAL_BASE_PATH=$B LD_LIBRARY_PATH=$B/lib OMP_NUM_THREADS=1
win=$(python3 -c "import json;print(len(json.load(open('$D/case/input/stimulus.json'))['windows']['training']))")
( ulimit -v ${VMEM_KB:-6291456}; timeout 10800 "$cli" graph "$D/case/groups/ordered.hal" "$D/case/groups/groups.json" "$D/case/input/recovered.json" \
    "$D/case/trace" "$D/case/graph" --window "$win" --profiles training --protocol "$D/case/input/protocol.json" ) > "$D/graph.log" 2>&1
( ulimit -v ${VMEM_KB:-6291456}; timeout 10800 "$B/c3_venv/bin/python" "$E/kernel_foldings/e8_score.py" "$D/case" "$G/truth.json" "$G/fold_top.json" \
    "$D/case/graph/graph_training.json" "$D/score.json" ) > "$D/score.log" 2>&1
echo "$case: $(tail -n 1 "$D/score.log" | cut -c1-400)"
